/* =====================================================
   LANGUAGE STATE
===================================================== */

const languages = ["mg", "fr", "en"];

let currentLanguage =
    localStorage.getItem("tanora-language") || "mg";



/* =====================================================
   CHANGE LANGUAGE
===================================================== */

function setLanguage(language) {

    if (!translations[language]) {
        language = "mg";
    }

    currentLanguage = language;


    /* Update every translated element */

    document
        .querySelectorAll("[data-i18n]")
        .forEach(element => {

            const key =
                element.getAttribute("data-i18n");

            const translation =
                translations[language][key];

            if (translation !== undefined) {

                element.textContent =
                    translation;

            }

        });


    /* Update HTML language */

    document.documentElement.lang =
        language;


    /* Update language button */

    const languageButton =
        document.getElementById("languageBtn");

    if (languageButton) {

        languageButton.textContent =
            language.toUpperCase();

    }


    /* Update page title */

    const titles = {

        mg:
            "TanOra — Mianara tsara kokoa. Mandrosoa isan'andro.",

        fr:
            "TanOra — Étudie mieux. Progresse chaque jour.",

        en:
            "TanOra — Study smarter. Progress every day."
    };

    document.title =
        titles[language];


    /* Save language */

    localStorage.setItem(
        "tanora-language",
        language
    );

}



/* =====================================================
   LANGUAGE BUTTON
===================================================== */

const languageButton =
    document.getElementById("languageBtn");

if (languageButton) {

    languageButton.addEventListener(
        "click",
        () => {

            const currentIndex =
                languages.indexOf(currentLanguage);

            const nextIndex =
                (currentIndex + 1) % languages.length;

            setLanguage(
                languages[nextIndex]
            );

        }
    );

}



